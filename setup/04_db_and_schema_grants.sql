SHOW FUTURE GRANTS IN SCHEMA PROD_ANALYTICS.MARTS;

-- Should list USAGE on PROD_RAW / PROD_ANALYTICS and the CREATE privileges
SHOW GRANTS TO ROLE SERVICE_ROLE;


USE ROLE SYSADMIN;
DROP SCHEMA IF EXISTS PROD_RAW.PUBLIC;
DROP SCHEMA IF EXISTS PROD_ANALYTICS.PUBLIC;
DROP SCHEMA IF EXISTS DEV_RAW.PUBLIC;
DROP SCHEMA IF EXISTS DEV_ANALYTICS.PUBLIC;