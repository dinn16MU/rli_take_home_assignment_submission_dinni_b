-- =====================================================================
-- 04: Databases, schemas and access grants
-- Role mapping used here:
--   TRANSFORMER   -> SERVICE_ROLE  (dbt service user)
--   DATA_ENGINEER -> DEVELOPER
--   ANALYST       -> ANALYST
-- =====================================================================


-- ---------------------------------------------------------------------
-- PART 1: Create databases and schemas (SYSADMIN)
-- ---------------------------------------------------------------------
USE ROLE SYSADMIN;

-- Prod: permanent, 7 days of Time Travel for recovery
CREATE DATABASE IF NOT EXISTS PROD_RAW       DATA_RETENTION_TIME_IN_DAYS = 7;
CREATE DATABASE IF NOT EXISTS PROD_ANALYTICS DATA_RETENTION_TIME_IN_DAYS = 7;

-- Dev: transient (no 7-day Fail-safe storage), 1 day of Time Travel.
-- Dev data can be rebuilt, so skipping Fail-safe saves cost.
CREATE TRANSIENT DATABASE IF NOT EXISTS DEV_RAW       DATA_RETENTION_TIME_IN_DAYS = 1;
CREATE TRANSIENT DATABASE IF NOT EXISTS DEV_ANALYTICS DATA_RETENTION_TIME_IN_DAYS = 1;

-- RAW schemas
CREATE SCHEMA IF NOT EXISTS PROD_RAW.INSURANCE;
CREATE SCHEMA IF NOT EXISTS DEV_RAW.INSURANCE;

-- ANALYTICS schemas: prod
CREATE SCHEMA IF NOT EXISTS PROD_ANALYTICS.STAGING;
CREATE SCHEMA IF NOT EXISTS PROD_ANALYTICS.MARTS;
CREATE SCHEMA IF NOT EXISTS PROD_ANALYTICS.SEMANTIC;
CREATE SCHEMA IF NOT EXISTS PROD_ANALYTICS.DQ;
CREATE SCHEMA IF NOT EXISTS PROD_ANALYTICS.GOVERNANCE;
-- Pipeline objects: deployed dbt project + scheduled tasks (no analyst access)
CREATE SCHEMA IF NOT EXISTS PROD_ANALYTICS.ORCHESTRATION;

-- ANALYTICS schemas: dev (schemas in a transient database are transient too)
CREATE SCHEMA IF NOT EXISTS DEV_ANALYTICS.STAGING;
CREATE SCHEMA IF NOT EXISTS DEV_ANALYTICS.MARTS;
CREATE SCHEMA IF NOT EXISTS DEV_ANALYTICS.SEMANTIC;
CREATE SCHEMA IF NOT EXISTS DEV_ANALYTICS.DQ;
CREATE SCHEMA IF NOT EXISTS DEV_ANALYTICS.GOVERNANCE;


-- ---------------------------------------------------------------------
-- PART 2: Grants (SECURITYADMIN, which has MANAGE GRANTS for future grants)
--
-- Notes:
-- * "ALL" grants cover objects that exist today; "FUTURE" grants cover
--   objects dbt creates later. Tables and views are granted separately.
-- * When dbt rebuilds a table (e.g. full refresh), future grants are
--   re-applied to the new object automatically.
-- * Future grants are set at SCHEMA level, not database level. If a
--   schema has any schema-level future grants, Snowflake ignores
--   database-level future grants for that schema, so mixing the two
--   would silently drop access in MARTS and DQ.
-- * SELECT on the semantic view is granted by dbt itself (on-run-end hook
--   in dbt_project.yml), because the view only exists after the first build.
-- ---------------------------------------------------------------------
USE ROLE SECURITYADMIN;


-- =========================
-- SERVICE_ROLE (TRANSFORMER)
-- =========================

-- PROD_RAW: usage only. Table privileges come in file 05.
GRANT USAGE ON DATABASE PROD_RAW           TO ROLE SERVICE_ROLE;
GRANT USAGE ON SCHEMA   PROD_RAW.INSURANCE TO ROLE SERVICE_ROLE;

-- PROD_ANALYTICS: build tables and views
GRANT USAGE ON DATABASE PROD_ANALYTICS TO ROLE SERVICE_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA PROD_ANALYTICS.STAGING  TO ROLE SERVICE_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA PROD_ANALYTICS.MARTS    TO ROLE SERVICE_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA PROD_ANALYTICS.DQ       TO ROLE SERVICE_ROLE;
GRANT USAGE, CREATE SEMANTIC VIEW      ON SCHEMA PROD_ANALYTICS.SEMANTIC TO ROLE SERVICE_ROLE;
-- Needed to reference (apply) the masking policy stored in GOVERNANCE
GRANT USAGE ON SCHEMA PROD_ANALYTICS.GOVERNANCE TO ROLE SERVICE_ROLE;
-- Owns the scheduled tasks (setup/07)
GRANT USAGE, CREATE TASK ON SCHEMA PROD_ANALYTICS.ORCHESTRATION TO ROLE SERVICE_ROLE;


-- Dev databases: none (dev runs as engineers)


-- ===========================
-- DEVELOPER (DATA_ENGINEER)
-- ===========================

-- PROD_RAW: read-only on INSURANCE
GRANT USAGE  ON DATABASE PROD_RAW                             TO ROLE DEVELOPER;
GRANT USAGE  ON SCHEMA   PROD_RAW.INSURANCE                   TO ROLE DEVELOPER;
GRANT SELECT ON ALL TABLES    IN SCHEMA PROD_RAW.INSURANCE    TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROD_RAW.INSURANCE    TO ROLE DEVELOPER;

-- PROD_ANALYTICS: read-only on every schema
GRANT USAGE ON DATABASE PROD_ANALYTICS                 TO ROLE DEVELOPER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE PROD_ANALYTICS  TO ROLE DEVELOPER;

-- STAGING
GRANT SELECT ON ALL TABLES    IN SCHEMA PROD_ANALYTICS.STAGING    TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROD_ANALYTICS.STAGING    TO ROLE DEVELOPER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROD_ANALYTICS.STAGING    TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROD_ANALYTICS.STAGING    TO ROLE DEVELOPER;

-- MARTS
GRANT SELECT ON ALL TABLES    IN SCHEMA PROD_ANALYTICS.MARTS      TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROD_ANALYTICS.MARTS      TO ROLE DEVELOPER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROD_ANALYTICS.MARTS      TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROD_ANALYTICS.MARTS      TO ROLE DEVELOPER;

-- SEMANTIC
GRANT SELECT ON ALL TABLES    IN SCHEMA PROD_ANALYTICS.SEMANTIC   TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROD_ANALYTICS.SEMANTIC   TO ROLE DEVELOPER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROD_ANALYTICS.SEMANTIC   TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROD_ANALYTICS.SEMANTIC   TO ROLE DEVELOPER;

-- DQ
GRANT SELECT ON ALL TABLES    IN SCHEMA PROD_ANALYTICS.DQ         TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROD_ANALYTICS.DQ         TO ROLE DEVELOPER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROD_ANALYTICS.DQ         TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROD_ANALYTICS.DQ         TO ROLE DEVELOPER;

-- GOVERNANCE
GRANT SELECT ON ALL TABLES    IN SCHEMA PROD_ANALYTICS.GOVERNANCE TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROD_ANALYTICS.GOVERNANCE TO ROLE DEVELOPER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROD_ANALYTICS.GOVERNANCE TO ROLE DEVELOPER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROD_ANALYTICS.GOVERNANCE TO ROLE DEVELOPER;

-- ORCHESTRATION: see task runs and errors for troubleshooting (can't change them)
GRANT MONITOR ON FUTURE TASKS IN SCHEMA PROD_ANALYTICS.ORCHESTRATION TO ROLE DEVELOPER;

-- Dev databases: create personal dev schemas for dbt
GRANT USAGE, CREATE SCHEMA ON DATABASE DEV_RAW       TO ROLE DEVELOPER;
GRANT USAGE, CREATE SCHEMA ON DATABASE DEV_ANALYTICS TO ROLE DEVELOPER;

-- Dev: full access on DEV_RAW.INSURANCE
GRANT ALL ON SCHEMA DEV_RAW.INSURANCE                     TO ROLE DEVELOPER;
GRANT ALL ON ALL TABLES    IN SCHEMA DEV_RAW.INSURANCE    TO ROLE DEVELOPER;
GRANT ALL ON FUTURE TABLES IN SCHEMA DEV_RAW.INSURANCE    TO ROLE DEVELOPER;
-- Dev dbt runs (as DEVELOPER) apply the dev copy of the masking policy
GRANT USAGE ON SCHEMA DEV_ANALYTICS.GOVERNANCE TO ROLE DEVELOPER;


-- =========
-- ANALYST
-- =========

-- PROD_ANALYTICS only
GRANT USAGE ON DATABASE PROD_ANALYTICS          TO ROLE ANALYST;
GRANT USAGE ON SCHEMA   PROD_ANALYTICS.MARTS    TO ROLE ANALYST;
GRANT USAGE ON SCHEMA   PROD_ANALYTICS.DQ       TO ROLE ANALYST;
GRANT USAGE ON SCHEMA   PROD_ANALYTICS.SEMANTIC TO ROLE ANALYST;

-- MARTS
GRANT SELECT ON ALL TABLES    IN SCHEMA PROD_ANALYTICS.MARTS TO ROLE ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROD_ANALYTICS.MARTS TO ROLE ANALYST;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROD_ANALYTICS.MARTS TO ROLE ANALYST;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROD_ANALYTICS.MARTS TO ROLE ANALYST;

-- DQ
GRANT SELECT ON ALL TABLES    IN SCHEMA PROD_ANALYTICS.DQ    TO ROLE ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROD_ANALYTICS.DQ    TO ROLE ANALYST;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROD_ANALYTICS.DQ    TO ROLE ANALYST;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROD_ANALYTICS.DQ    TO ROLE ANALYST;

-- SEMANTIC: USAGE above; SELECT on the semantic view comes from dbt (see PART 2 notes)


-- ---------------------------------------------------------------------
-- PART 3: Account-level privilege to run tasks (ACCOUNTADMIN only)
-- ---------------------------------------------------------------------
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SERVICE_ROLE;


